class StoragePressure(str, Enum):
    NOMINAL = "NOMINAL"
    MODERATE = "MODERATE"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


@dataclass
class FleetDataProduct:
    """Individual data product record generated by an exploration unit."""
    product_id: str
    rover_id: str
    target_id: str
    instrument_id: str
    mode_name: str
    size_bytes: int
    size_mb: float
    creation_met_s: float
    is_transferred: bool = False
    transfer_met_s: Optional[float] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "product_id": self.product_id,
            "rover_id": self.rover_id,
            "target_id": self.target_id,
            "instrument_id": self.instrument_id,
            "mode_name": self.mode_name,
            "size_bytes": self.size_bytes,
            "size_mb": round(self.size_mb, 2),
            "creation_met_s": round(self.creation_met_s, 1),
            "is_transferred": self.is_transferred,
            "transfer_met_s": round(self.transfer_met_s, 1) if self.transfer_met_s is not None else None,
        }


@dataclass
class RoverResourceAudit:
    """Detailed resource breakdown for a single rover."""
    rover_id: str
    battery_capacity_wh: float
    current_energy_wh: float
    consumed_energy_wh: float
    battery_soc_pct: float
    reserve_margin_pct: float
    reserve_threshold_wh: float
    is_feasible: bool
    energy_drive_wh: float
    energy_base_avionics_wh: float
    energy_instruments_wh: float
    energy_communications_wh: float
    storage_capacity_mb: float
    used_storage_mb: float
    storage_utilization_pct: float
    storage_pressure: str
    data_backlog_mb: float
    data_products_count: int

    def to_dict(self) -> Dict[str, Any]:
        return {
            "rover_id": self.rover_id,
            "battery_capacity_wh": self.battery_capacity_wh,
            "current_energy_wh": round(self.current_energy_wh, 2),
            "consumed_energy_wh": round(self.consumed_energy_wh, 2),
            "battery_soc_pct": round(self.battery_soc_pct, 2),
            "reserve_margin_pct": round(self.reserve_margin_pct, 2),
            "reserve_threshold_wh": round(self.reserve_threshold_wh, 2),
            "is_feasible": self.is_feasible,
            "breakdown": {
                "drive_wh": round(self.energy_drive_wh, 2),
                "base_avionics_wh": round(self.energy_base_avionics_wh, 2),
                "instruments_wh": round(self.energy_instruments_wh, 2),
                "communications_wh": round(self.energy_communications_wh, 2),
            },
            "storage": {
                "capacity_mb": self.storage_capacity_mb,
                "used_mb": round(self.used_storage_mb, 2),
                "utilization_pct": round(self.storage_utilization_pct, 2),
                "pressure": self.storage_pressure,
                "backlog_mb": round(self.data_backlog_mb, 2),
                "products_count": self.data_products_count,
            }
        }


class FleetResourceManager:
    """
    Consolidates resource ledgers across the exploration fleet.
    Strictly forbids cross-rover energy pooling while tracking finite downlink capacity.
    """

    def __init__(self, downlink_bandwidth_mbps: float = 2.0):
        # 2.0 Mbps = 0.25 MB/s total shared transfer throughput
        self.downlink_rate_mbs = downlink_bandwidth_mbps / 8.0

    def compute_rover_energy_consumption(
        self,
        rover_config: RoverUnitConfig,
        route: FleetRoverRoute,
        assigned_targets: List[FleetScienceTarget]
    ) -> RoverResourceAudit:
        """
        Calculates physical energy consumption breakdown for a single rover
        over its route and observation activities.
        """
        # 1. Drive Energy: (Base Power + Moving Drive Power) * Drive Time
        drive_time_s = route.traverse_time_s
        drive_power_w = 140.0  # mechanical traction power
        energy_drive_wh = (drive_power_w * drive_time_s) / 3600.0

        # 2. Base Avionics Energy: base_electrical_load_w * total_mission_time
        total_time_s = route.total_time_s
        energy_base_wh = (rover_config.base_electrical_load_w * total_time_s) / 3600.0

        # 3. Instrument Energy: Sum of observation mode energy for each target
        energy_inst_wh = 0.0
        used_storage_mb = 0.0
        products_count = 0

        for tgt in assigned_targets:
            # Find matching instrument mode
            inst_p = None
            for cat_key, p in INSTRUMENT_CATALOG.items():
                if p.instrument_id.value in rover_config.instrument_ids:
                    if any(obj.value == tgt.objective for obj in p.compatible_objectives):
                        inst_p = p
                        break
            if inst_p:
                energy_inst_wh += inst_p.energy_wh
                used_storage_mb += inst_p.expected_data_bytes / (1024 * 1024)
                products_count += 1
            else:
                energy_inst_wh += 20.0
                used_storage_mb += 15.0
                products_count += 1

        # 4. Communications Energy: Standby 20W + Active Transmit 65W
        energy_comm_wh = ((20.0 * total_time_s) + (65.0 * 600.0)) / 3600.0

        total_consumed_wh = energy_drive_wh + energy_base_wh + energy_inst_wh + energy_comm_wh
        current_energy_wh = max(0.0, rover_config.usable_battery_capacity_wh - total_consumed_wh)
        soc_pct = (current_energy_wh / rover_config.usable_battery_capacity_wh) * 100.0

        reserve_th_wh = rover_config.usable_battery_capacity_wh * (rover_config.reserve_margin_pct / 100.0)
        is_feasible = current_energy_wh >= reserve_th_wh

        storage_util_pct = (used_storage_mb / rover_config.storage_capacity_mb) * 100.0
        pressure = (
            StoragePressure.CRITICAL.value if storage_util_pct > 90.0
            else (StoragePressure.HIGH.value if storage_util_pct > 75.0
                  else (StoragePressure.MODERATE.value if storage_util_pct > 50.0
                        else StoragePressure.NOMINAL.value))
        )

        return RoverResourceAudit(
            rover_id=rover_config.rover_id,
            battery_capacity_wh=rover_config.usable_battery_capacity_wh,
            current_energy_wh=current_energy_wh,
            consumed_energy_wh=total_consumed_wh,
            battery_soc_pct=soc_pct,
            reserve_margin_pct=soc_pct - rover_config.reserve_margin_pct,
            reserve_threshold_wh=reserve_th_wh,
            is_feasible=is_feasible,
            energy_drive_wh=energy_drive_wh,
            energy_base_avionics_wh=energy_base_wh,
            energy_instruments_wh=energy_inst_wh,
            energy_communications_wh=energy_comm_wh,
            storage_capacity_mb=rover_config.storage_capacity_mb,
            used_storage_mb=used_storage_mb,
            storage_utilization_pct=storage_util_pct,
            storage_pressure=pressure,
            data_backlog_mb=used_storage_mb,
            data_products_count=products_count,
        )

    def evaluate_fleet_resources(
        self,
        rovers: Dict[str, RoverUnitConfig],
        routes: Dict[str, FleetRoverRoute],
        allocations: Dict[str, List[str]],
        targets_by_id: Dict[str, FleetScienceTarget]
    ) -> Tuple[Dict[str, RoverResourceAudit], Dict[str, Any]]:
        """
        Evaluates independent resource states across all rovers and returns
        both per-rover audits and a reconciled fleet-level summary.
        """
        audits: Dict[str, RoverResourceAudit] = {}
        for r_id, r_cfg in rovers.items():
            route = routes.get(r_id)
            if not route:
                continue
            t_ids = allocations.get(r_id, [])
            tgt_objs = [targets_by_id[t_id] for t_id in t_ids if t_id in targets_by_id]
            audits[r_id] = self.compute_rover_energy_consumption(r_cfg, route, tgt_objs)

        # Aggregate Fleet Totals (strict accounting: no energy pooling)
        total_cap_wh = sum(a.battery_capacity_wh for a in audits.values())
        total_consumed_wh = sum(a.consumed_energy_wh for a in audits.values())
        total_remain_wh = sum(a.current_energy_wh for a in audits.values())
        min_soc = min((a.battery_soc_pct for a in audits.values()), default=100.0)
        total_used_storage = sum(a.used_storage_mb for a in audits.values())
        total_backlog = sum(a.data_backlog_mb for a in audits.values())
        constrained_count = sum(1 for a in audits.values() if not a.is_feasible)

        fleet_summary = {
            "total_battery_capacity_wh": round(total_cap_wh, 2),
            "total_energy_consumed_wh": round(total_consumed_wh, 2),
            "total_energy_remaining_wh": round(total_remain_wh, 2),
            "min_rover_soc_pct": round(min_soc, 2),
            "total_used_storage_mb": round(total_used_storage, 2),
            "total_data_backlog_mb": round(total_backlog, 2),
            "constrained_rovers_count": constrained_count,
            "fleet_resource_status": "FEASIBLE" if constrained_count == 0 else "CONSTRAINED",
        }

        return audits, fleet_summary
